#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-LICENSES at the repo root — third-party notices
 * for what actually ships inside the friends-build zip (Epic 14).
 *
 * Scope: npm production dependencies (bundled into the frontend JS) +
 * Python runtime dependencies (numpy, pillow, onnxruntime — bundled into the frozen
 * sidecar) + PyInstaller itself (its compiled bootloader is embedded in
 * the frozen sidecar executable, under its own bootloader exception —
 * see guidance/projects/oblique/design/licensing.md) + the
 * `sidecar/kernels` Rust crate's own dependency tree (its `.so` ships
 * inside the frozen sidecar — Epic 19). `src-tauri`'s crate tree is NOT
 * enumerated here — few hundred transitive crates, licence policy for
 * that tree is still manual review per licensing.md (its automated gate,
 * `scripts/check_rust_licenses.py`, only covers `sidecar/kernels` for the
 * same reason); revisit if/when the "first public release" epic needs a
 * full legal notices file.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const PYTHON_RUNTIME = new Set(['numpy', 'pillow', 'onnxruntime']);
const PYTHON_EMBEDDED_TOOLING = new Set(['pyinstaller']);

function npmPackages() {
  const raw = execFileSync('pnpm', ['licenses', 'list', '--json', '--prod'], { encoding: 'utf8' });
  const byLicence = JSON.parse(raw);
  const packages = [];
  for (const [licence, pkgs] of Object.entries(byLicence)) {
    for (const pkg of pkgs) {
      packages.push({ name: pkg.name, version: pkg.versions?.[0] ?? '', licence });
    }
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

function pythonPackages() {
  const raw = execFileSync('uv', ['run', 'pip-licenses', '--format=json'], {
    encoding: 'utf8',
    cwd: 'sidecar',
  });
  const all = JSON.parse(raw);
  return all
    .filter((pkg) => {
      const name = pkg.Name.toLowerCase();
      return PYTHON_RUNTIME.has(name) || PYTHON_EMBEDDED_TOOLING.has(name);
    })
    .map((pkg) => ({
      name: pkg.Name,
      version: pkg.Version,
      licence: pkg.License,
      note: PYTHON_EMBEDDED_TOOLING.has(pkg.Name.toLowerCase())
        ? ' (compiled bootloader embedded under its bootloader exception — see design/licensing.md)'
        : '',
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function rustKernelsPackages() {
  const raw = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--manifest-path', 'sidecar/kernels/Cargo.toml'],
    { encoding: 'utf8' },
  );
  const { packages } = JSON.parse(raw);
  return packages
    .map((pkg) => ({ name: pkg.name, version: pkg.version, licence: pkg.license ?? '(no licence field)' }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

const npm = npmPackages();
const python = pythonPackages();
const rustKernels = rustKernelsPackages();

const lines = [
  'THIRD-PARTY-LICENSES',
  '',
  'Third-party software distributed as part of this build.',
  'Generated by scripts/generate-third-party-licenses.mjs — do not edit by hand.',
  '',
  '== JavaScript / TypeScript (npm, production dependencies) ==',
  '',
  ...npm.map((pkg) => `${pkg.name} ${pkg.version} — ${pkg.licence}`),
  '',
  '== Python (sidecar runtime + embedded build tooling) ==',
  '',
  ...python.map((pkg) => `${pkg.name} ${pkg.version} — ${pkg.licence}${pkg.note}`),
  '',
  '== Rust (sidecar/kernels native extension, embedded in the frozen sidecar) ==',
  '',
  ...rustKernels.map((pkg) => `${pkg.name} ${pkg.version} — ${pkg.licence}`),
  '',
];

writeFileSync('THIRD-PARTY-LICENSES', lines.join('\n'));
console.log(
  `THIRD-PARTY-LICENSES written: ${npm.length} npm packages, ${python.length} Python packages, ${rustKernels.length} Rust crates.`,
);
